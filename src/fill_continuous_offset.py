def _build_continuous_path(contours_by_level: Dict[int, List[LineString]],
                           breakpoints: List[Tuple[int, LineString, Point, LineString, Point]]) -> LineString:
    """
    Connects contours using breakpoints to form a single continuous path.

    Args:
        contours_by_level: Dict mapping level index to list of LineString contours.
        breakpoints: List of breakpoint tuples generated by _find_breakpoints.

    Returns:
        A single LineString representing the continuous toolpath, or None if failed.
    """
    if not breakpoints:
        print("Warning: No breakpoints provided, cannot build continuous path.")
        # Handle case with only one contour level (e.g., return the contour itself?)
        levels = sorted(contours_by_level.keys())
        if len(levels) == 1 and contours_by_level[levels[0]]:
            # Return the first contour of the only level if no breakpoints needed
            return contours_by_level[levels[0]][0]
        return None

    final_path_coords = []
    processed_contours = set() # Keep track of contours already traversed

    # Sort breakpoints by level to process connections sequentially
    breakpoints.sort(key=lambda x: x[0])

    # Start with the first breakpoint connection
    level, outer_contour, p_outer, inner_contour, p_inner = breakpoints[0]

    # --- Handle the very first contour (outermost) ---
    # Traverse the first outer contour starting from its breakpoint
    traversal_coords = _traverse_contour_from_point(outer_contour, p_outer)
    if traversal_coords:
        final_path_coords.extend(traversal_coords)
        processed_contours.add(outer_contour.wkt) # Use WKT for hashable representation
    else:
        print(f"Error: Failed to traverse initial outer contour at level {level}")
        return None

    # Add the first connection segment (outer breakpoint to inner breakpoint)
    # The traversal already ends at p_outer (or closest vertex), directly add p_inner
    final_path_coords.append((p_inner.x, p_inner.y))

    # --- Iterate through the remaining connections ---
    for i in range(len(breakpoints)):
        level, current_contour, p_current_break, next_contour, p_next_break = breakpoints[i]

        # Traverse the current_contour (which was the 'inner' contour of the previous step)
        # starting from its breakpoint p_current_break
        if current_contour.wkt not in processed_contours:
            traversal_coords = _traverse_contour_from_point(current_contour, p_current_break)
            if traversal_coords:
                # Ensure the traversal starts near p_current_break and ends there.
                # The list should contain the full loop.
                final_path_coords.extend(traversal_coords[1:]) # Skip first point (already added)
                processed_contours.add(current_contour.wkt)
            else:
                print(f"Error: Failed to traverse contour at level {level}")
                # Decide how to handle failure: stop or try to continue?
                continue # Skip this contour for now

        # Add the connection segment to the *next* contour's breakpoint
        # Check if there is a next breakpoint involving this 'next_contour'
        if i + 1 < len(breakpoints):
             # Find the breakpoint where 'next_contour' acts as the outer part
             next_break_info = None
             for bp in breakpoints[i+1:]:
                 if bp[1] == next_contour: # If next_contour is the outer contour in a future breakpoint
                     next_break_info = bp
                     break

             if next_break_info:
                 # Connect from current position (end of traversal = p_current_break)
                 # to the breakpoint on the next_contour (p_next_break)
                 final_path_coords.append((p_next_break.x, p_next_break.y))
             else:
                 # This 'next_contour' is the innermost in this chain, traverse it last
                 pass # Will be handled after loop
        else:
             # This is the last breakpoint, 'next_contour' is the innermost
             # Connect to its breakpoint p_next_break
             final_path_coords.append((p_next_break.x, p_next_break.y))


    # --- Handle the very last contour (innermost) ---
    # The last breakpoint processed was (level, current_contour, p_current, next_contour, p_next)
    # We are now at p_next on next_contour (the innermost one). Traverse it.
    last_contour = breakpoints[-1][3] # The 'inner_contour' of the last breakpoint
    last_breakpoint = breakpoints[-1][4] # The 'breakpoint_inner' of the last breakpoint

    if last_contour.wkt not in processed_contours:
        traversal_coords = _traverse_contour_from_point(last_contour, last_breakpoint)
        if traversal_coords:
            # Add traversal, skipping the first point (already at last_breakpoint)
            final_path_coords.extend(traversal_coords[1:])
            processed_contours.add(last_contour.wkt)
        else:
            print(f"Error: Failed to traverse final inner contour at level {breakpoints[-1][0]+1}")
            # Path might be incomplete

    if not final_path_coords:
        print("Error: No path coordinates generated.")
        return None

    # Create the final LineString
    try:
        final_path = LineString(final_path_coords)
        if not final_path.is_valid:
             print("Warning: Generated continuous path is not valid. Attempting buffer(0).")
             final_path = final_path.buffer(0) # Clean up potential self-intersections near connections
             if not isinstance(final_path, LineString): # Buffer(0) might return Polygon/MultiLineString
                 print("Error: Path cleanup resulted in non-LineString geometry.")
                 # Fallback: return original coords? Or handle MultiLineString?
                 # For now, return None if cleanup fails badly.
                 return None
        return final_path
    except Exception as e:
        print(f"Error creating final LineString: {e}")
        return None
