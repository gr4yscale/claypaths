def _get_point_on_line_closest_to_point(target_point: Point, line: LineString) -> Point:
    """Finds the point on a LineString closest to a target Point."""
    if not isinstance(target_point, Point) or not isinstance(line, LineString):
        raise ValueError("Inputs must be Shapely Point and LineString")
    if line.is_empty:
        return None
    # Project the point onto the line and interpolate to get the point
    distance = line.project(target_point)
    closest_point = line.interpolate(distance)
    return closest_point

def _find_closest_points_between_lines(line1: LineString, line2: LineString) -> Tuple[Point, Point]:
    """
    Finds the pair of points (one on each line) that are closest to each other.
    Uses shapely.ops.nearest_points.
    """
    if not isinstance(line1, LineString) or not isinstance(line2, LineString) or line1.is_empty or line2.is_empty:
        # Return None or raise error if lines are invalid
        return None, None
    try:
        p1, p2 = nearest_points(line1, line2)
        return p1, p2
    except Exception as e:
        print(f"Warning: Could not find nearest points between lines: {e}")
        # Fallback or error handling: maybe return centroids or None
        return None, None


def _traverse_contour_from_point(contour: LineString, start_point: Point) -> List[Tuple[float, float]]:
    """
    Reorders the coordinates of a closed contour (LineString) to start
    near the specified start_point and traverse the loop.

    Args:
        contour: The closed LineString (should have matching start/end points).
        start_point: The Point near which the traversal should begin.

    Returns:
        A list of coordinate tuples representing the traversed path.
        Returns None if contour is invalid.
    """
    if not contour or contour.is_empty or len(contour.coords) < 3:
        return None # Cannot traverse an empty or too short line

    coords = list(contour.coords)
    if coords[0] != coords[-1]:
         # If not explicitly closed, close it for traversal logic
         coords.append(coords[0])

    # Find the index of the vertex closest to the start_point
    min_dist = float('inf')
    start_index = 0
    for i, pt_coords in enumerate(coords[:-1]): # Exclude the closing point for index finding
        dist = start_point.distance(Point(pt_coords))
        if dist < min_dist:
            min_dist = dist
            start_index = i

    # Reorder coordinates: start from start_index, wrap around, end at start_index
    # Exclude the repeated start point at the very end of the list
    reordered_coords = coords[start_index:-1] + coords[:start_index+1]

    # Ensure the start point is *exactly* the first point if needed,
    # or handle potential floating point issues if start_point isn't exactly a vertex.
    # For now, starting at the *closest vertex* is sufficient.

    return reordered_coords


