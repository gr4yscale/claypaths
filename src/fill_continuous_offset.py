def generate_continuous_offset_fill(polygon: Polygon, toolpath_width: float):
    """
    Generates a continuous toolpath for a polygon using iterative offsetting
    and breakpoint connections, based on the described algorithm.

    Args:
        polygon: The Shapely Polygon to fill (must have exterior, may have interiors).
        toolpath_width: The distance between toolpaths (offset distance).

    Returns:
        A single Shapely LineString representing the continuous toolpath,
        or None if filling is not possible.
    """
    if not isinstance(polygon, Polygon) or polygon.is_empty:
        print("Warning: Invalid or empty polygon provided for continuous offset fill.")
        return None

    all_contours = []
    current_polygon = polygon

    # 1. Contour Offsetting (Iterative Inward Offsetting)
    level = 0
    while True:
        # Perform inward offset
        # Note: Negative offset for inward direction
        offset_polygon = current_polygon.buffer(-toolpath_width, join_style=2) # MITRE join

        # Clean up potential small artifacts or invalid geometries
        if not offset_polygon.is_valid:
            offset_polygon = offset_polygon.buffer(0)

        if offset_polygon.is_empty or not isinstance(offset_polygon, (Polygon, MultiPolygon)):
            break # Stop if offset results in nothing or non-polygonal shapes

        contours_at_level = []
        if isinstance(offset_polygon, Polygon):
            # Add exterior
            if not offset_polygon.exterior.is_empty:
                 contours_at_level.append(offset_polygon.exterior)
            # Add interiors (holes generated by offsetting)
            # These become "outer" contours for the *next* iteration's perspective
            # but are stored as LineStrings here.
            for interior in offset_polygon.interiors:
                 if not interior.is_empty:
                     contours_at_level.append(interior)

        elif isinstance(offset_polygon, MultiPolygon):
             for poly in offset_polygon.geoms:
                 if isinstance(poly, Polygon):
                     if not poly.exterior.is_empty:
                         contours_at_level.append(poly.exterior)
                     for interior in poly.interiors:
                         if not interior.is_empty:
                             contours_at_level.append(interior)

        if not contours_at_level:
            break # No valid contours generated at this level

        # Store contours with their level (higher level means further inside)
        all_contours.extend([(level, contour) for contour in contours_at_level])

        # Prepare for next iteration: the offset polygon becomes the new boundary
        current_polygon = offset_polygon
        level += 1

    if not all_contours:
        print("Warning: No offset contours generated.")
        return None

    # Add the original polygon's boundary (level -1, conceptually)
    # We need both exterior and interiors as starting contours
    initial_contours = [polygon.exterior] + list(polygon.interiors)
    all_contours = [(-1, initial) for initial in initial_contours] + all_contours

    # Re-level contours (Algorithm 1 is implicitly handled by iterative offsetting)
    # Sort contours primarily by level (descending, so innermost is first)
    # Secondary sort could be added if needed (e.g., by area if multiple contours at same level)
    # For now, the iterative generation order should suffice if we process level by level.
    # Let's reverse the list so outermost is first (level -1, 0, 1, ...)
    all_contours.sort(key=lambda item: item[0]) # Sort by level ascending (-1, 0, 1, ...)

    print(f"Generated {len(all_contours)} total contours across {level+1} effective levels (including original).")

    if not all_contours:
        return None # No contours to process

    # Group contours by level
    contours_by_level: Dict[int, List[LineString]] = {}
    for lvl, contour in all_contours:
        # Ensure contours are LineStrings for consistency
        if isinstance(contour, LinearRing):
             contour_line = LineString(contour.coords)
        elif isinstance(contour, LineString):
             contour_line = contour
        else:
             print(f"Warning: Skipping unexpected geometry type in contours: {type(contour)}")
             continue

        if lvl not in contours_by_level:
            contours_by_level[lvl] = []
        contours_by_level[lvl].append(contour_line)

    # Handle case with only one level (no offsetting possible or needed)
    if len(contours_by_level) <= 1:
         print("Only one contour level found, returning the original contour(s).")
         # Return the original polygon boundary(ies) as a MultiLineString or single LineString
         original_level = min(contours_by_level.keys())
         if len(contours_by_level[original_level]) == 1:
             return contours_by_level[original_level][0]
         else:
             return MultiLineString(contours_by_level[original_level])


    # 2. Finding Breakpoints
    print("Step 2: Finding breakpoints between adjacent contours...")
    breakpoints = _find_breakpoints(contours_by_level, toolpath_width)

    if not breakpoints:
        print("Warning: Could not find any breakpoints. Returning raw contours.")
        # Fallback: return the contours as separate lines
        all_lines = [line for lvl_lines in contours_by_level.values() for line in lvl_lines]
        if len(all_lines) == 1:
            return all_lines[0]
        elif len(all_lines) > 1:
            return MultiLineString(all_lines)
        else:
            return None

    # 3. Generating Continuous Path (combines forming sub-paths and connecting)
    print("Step 3: Building continuous path...")
    continuous_path = _build_continuous_path(contours_by_level, breakpoints)

    if continuous_path:
        print("Successfully generated continuous path.")
        # Optional visualization call:
        # visualize_contours_and_path(polygon, continuous_path, "Continuous Offset Fill")
    else:
        print("Failed to generate continuous path.")
        # Fallback? Return raw contours?
        all_lines = [line for lvl_lines in contours_by_level.values() for line in lvl_lines]
        if len(all_lines) == 1: return all_lines[0]
        elif len(all_lines) > 1: return MultiLineString(all_lines)
        else: return None


    return continuous_path


def visualize_contours_and_path(polygon, path, title="Continuous Offset Fill"):
    """Helper function to visualize the polygon and the generated path."""
    fig, ax = plt.subplots(figsize=(8, 8))
    ax.set_aspect('equal', adjustable='box')

    # Plot polygon
    if polygon:
        x, y = polygon.exterior.xy
        ax.plot(x, y, color='black', linewidth=1, solid_capstyle='round', label='Original Polygon')
        for interior in polygon.interiors:
            xi, yi = interior.xy
            ax.plot(xi, yi, color='grey', linewidth=1, solid_capstyle='round')

    # Plot path
    if path:
        if isinstance(path, LineString):
            xp, yp = path.xy
            ax.plot(xp, yp, color='blue', linewidth=1.5, solid_capstyle='round', label='Toolpath')
        elif isinstance(path, MultiLineString):
             for line in path.geoms:
                 xp, yp = line.xy
                 ax.plot(xp, yp, color='blue', linewidth=1.5, solid_capstyle='round')


    ax.set_title(title)
    ax.legend()
    plt.show()

